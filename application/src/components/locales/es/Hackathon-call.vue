  </ul>
  <p>Se podrán inscribir hasta 14 equipos, con un máximo de 4 participantes por equipo. Cada equipo elegirá una persona representante. Puedes inscribirte aunque no tengas equipo completo; durante el evento se apoyará la formación de equipos.</p>

  <h2>4. Reto del hackatón</h2>
  <p><strong>Reto principal:</strong> Diseño de Interfaces para Transporte Público Inclusivo.</p>
  <p>La tarea consiste en diseñar o rediseñar una aplicación móvil relacionada con transporte público y movilidad urbana en Oaxaca, ayudando a las personas a moverse con mayor facilidad y comprender mejor la información del transporte.</p>
  <p>La idea no tiene que estar programada ni ser perfecta. Debe mostrar claramente cómo funcionaría y por qué ayudaría a las personas.</p>
  <h3>La solución puede incluir ideas para</h3>
  <ul>
    <li>Consultar rutas</li>
    <li>Ver recorridos</li>
    <li>Saber tiempos aproximados de llegada</li>
    <li>Entender transbordos</li>
    <li>Recibir avisos o notificaciones</li>
    <li>Identificar paradas cercanas</li>
    <li>Usar la app con internet limitado</li>
    <li>Apoyar a personas adultas mayores</li>
    <li>Apoyar a personas con poca experiencia usando tecnología</li>
    <li>Apoyar a turistas o visitantes</li>
    <li>Apoyar a personas con discapacidad</li>
  </ul>

  <h2>5. Uso de Inteligencia Artificial</h2>
  <p>Sí está permitido usar herramientas de Inteligencia Artificial. Uno de los objetivos del hackatón es aprender a usar la IA como apoyo para diseñar mejores soluciones.</p>
  <p>La IA puede ayudar a pensar, organizar ideas, crear ejemplos, mejorar textos, generar imágenes, explorar alternativas y preparar la presentación.</p>
  <p>La propuesta final debe mostrar la creatividad, el criterio y las decisiones del equipo participante.</p>
  <h3>La IA se puede usar para</h3>
  <ul>
    <li>Generar ideas iniciales</li>
    <li>Analizar un problema</li>
    <li>Crear nombres o conceptos para la solución</li>
    <li>Redactar textos más claros</li>
    <li>Proponer preguntas para usuarios</li>
    <li>Organizar información</li>
    <li>Generar bocetos visuales</li>
    <li>Crear imágenes de referencia</li>
    <li>Mejorar una presentación</li>
    <li>Revisar ortografía y redacción</li>
    <li>Pensar en problemas de accesibilidad</li>
    <li>Comparar alternativas de diseño</li>
  </ul>
