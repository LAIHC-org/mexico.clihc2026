  <h2>9. Glosario rápido</h2>
  <ul>
    <li><strong>HCI:</strong> Interacción Humano-Computadora: cómo las personas usan la tecnología y cómo podemos diseñarla mejor.</li>
    <li><strong>UX:</strong> Experiencia de Usuario: cómo se siente una persona al usar una app, sitio web o servicio digital.</li>
    <li><strong>Usabilidad:</strong> Que algo sea fácil de usar, fácil de entender y útil.</li>
    <li><strong>Accesibilidad:</strong> Diseñar para que más personas puedan usar una solución, incluyendo personas con discapacidad, personas adultas mayores o personas con poca experiencia tecnológica.</li>
    <li><strong>Persona:</strong> Descripción de un tipo de usuario que ayuda a imaginar para quién estamos diseñando.</li>
    <li><strong>Flujo de usuario:</strong> Recorrido o lista de pasos que sigue una persona para completar una tarea.</li>
    <li><strong>Wireframe:</strong> Dibujo simple de una pantalla para organizar botones, textos e información.</li>
    <li><strong>Mockup:</strong> Pantalla más elaborada que muestra cómo podría verse el diseño.</li>
    <li><strong>Prototipo:</strong> Versión de prueba de la solución, interactiva o visual.</li>
    <li><strong>Pitch:</strong> Presentación breve para explicar una idea de forma clara y convincente.</li>
  </ul>

