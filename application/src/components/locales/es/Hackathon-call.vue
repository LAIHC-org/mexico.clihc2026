  <h2>1. ¿Qué es este hackatón?</h2>
  <p>El Hackatón de Experiencia de Usuario e Inteligencia Artificial es una actividad oficial dentro del XII Congreso Latinoamericano de Interacción Humano-Computadora (CLIHC 2026), que se realizará en la ciudad de Oaxaca, México.</p>
  <p>Está dirigido a estudiantes de bachillerato, universidad y posgrado que quieran imaginar, diseñar y presentar soluciones tecnológicas útiles para la vida real.</p>
  <p>No necesitas ser experto en programación, diseño o IA. Lo central es aprender, trabajar en equipo y proponer ideas que ayuden a las personas.</p>
  <p>Durante el hackatón aprenderás a pensar y diseñar tecnología centrada en las personas: entender problemas reales, identificar usuarios y crear propuestas claras, útiles, accesibles e inclusivas.</p>

  <h2>2. Objetivo y enfoque general</h2>
  <p>El objetivo es diseñar una propuesta tecnológica para mejorar servicios públicos digitales relacionados con movilidad y transporte público en la ciudad de Oaxaca.</p>
  <p>La propuesta debe mostrar cómo una aplicación podría ser más fácil de usar, más clara, más accesible y más útil para sus usuarios.</p>
  <p>El enfoque no es programar una app completa, sino entender un problema real, pensar en quienes lo viven, diseñar una solución, crear pantallas o prototipos, usar herramientas digitales e IA de forma creativa y responsable y presentar la propuesta claramente ante un jurado.</p>

  <h2>3. ¿Quiénes pueden participar y cómo se forman los equipos?</h2>
  <p>Pueden participar estudiantes de bachillerato o preparatoria, universidad y posgrado.</p>
  <p>El hackatón está abierto a personas interesadas en diseño, tecnología, programación, comunicación, psicología, educación, arte digital, ciencias sociales, inteligencia artificial, transporte, movilidad o solución de problemas sociales.</p>
  <p>No pasa nada si tu área no aparece en la lista: si tienes interés en participar, puedes hacerlo.</p>
  <h3>Áreas recomendadas</h3>
  <ul>
