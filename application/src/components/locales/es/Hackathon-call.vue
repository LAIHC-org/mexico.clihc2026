  <h3>Paso 2: Pensar en los usuarios</h3>
  <ul>
    <li>Una estudiante que usa transporte público para ir a la escuela</li>
    <li>Una persona adulta mayor que no usa mucho el celular</li>
    <li>Una persona que visita Oaxaca por primera vez</li>
    <li>Una persona que necesita llegar rápido a una cita médica</li>
    <li>Una persona con discapacidad visual</li>
    <li>Una madre o padre que viaja con niñas o niños</li>
  </ul>
  <h3>Paso 3: Diseñar el recorrido de uso</h3>
  <ol>
    <li>La persona abre la aplicación.</li>
    <li>Escribe a dónde quiere ir.</li>
    <li>La app muestra rutas disponibles.</li>
    <li>La persona elige una ruta.</li>
    <li>La app muestra el tiempo estimado.</li>
    <li>La app avisa dónde bajar.</li>
  </ol>
