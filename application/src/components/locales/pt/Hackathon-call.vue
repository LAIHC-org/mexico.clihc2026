  <h2>4. Desafio do hackathon</h2>
  <p><strong>Desafio principal:</strong> Design de Interfaces para Transporte Público Inclusivo.</p>
  <p>As equipes devem desenhar ou redesenhar um aplicativo móvel relacionado ao transporte público e à mobilidade urbana em Oaxaca, ajudando as pessoas a se deslocarem com mais facilidade e a entenderem melhor as informações do transporte.</p>
  <p>A ideia não precisa estar programada nem ser perfeita. Ela deve mostrar claramente como funcionaria e por que ajudaria as pessoas.</p>
