  <h2>1. O que é este hackathon?</h2>
  <p>O Hackathon de Experiência do Usuário e Inteligência Artificial é uma atividade oficial do XII Congresso Latino-Americano de Interação Humano-Computador (CLIHC 2026), a ser realizado em Oaxaca, México.</p>
  <p>Ele foi pensado para estudantes do ensino médio, graduação e pós-graduação que queiram imaginar, projetar e apresentar soluções tecnológicas úteis para a vida real.</p>
  <p>Você não precisa ser especialista em programação, design ou IA. O principal é aprender, trabalhar em equipe e propor ideias que ajudem as pessoas.</p>
  <p>Durante o hackathon, você aprenderá a pensar como designer de tecnologia centrada nas pessoas: observar problemas reais, entender usuários e criar propostas claras, úteis, acessíveis e inclusivas.</p>

  <h2>2. Objetivo e abordagem geral</h2>
  <p>O objetivo é desenhar uma proposta tecnológica para melhorar serviços públicos digitais relacionados à mobilidade e ao transporte público na cidade de Oaxaca.</p>
  <p>A proposta deve mostrar como um aplicativo poderia ser mais fácil de usar, mais claro, mais acessível e mais útil para seus usuários.</p>
  <p>O foco principal não é programar um aplicativo completo. O foco é entender um problema real, pensar nas pessoas que o vivenciam, desenhar uma solução possível, criar telas ou protótipos, usar ferramentas digitais e IA de forma criativa e responsável e apresentar a proposta com clareza a um júri.</p>

