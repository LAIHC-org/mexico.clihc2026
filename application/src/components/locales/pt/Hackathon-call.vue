  <h2>9. Glossário rápido</h2>
  <ul>
    <li><strong>HCI:</strong> Interação Humano-Computador: como as pessoas usam tecnologia e como podemos desenhá-la melhor.</li>
    <li><strong>UX:</strong> Experiência do Usuário: como uma pessoa se sente ao usar um aplicativo, site ou serviço digital.</li>
    <li><strong>Usabilidade:</strong> Algo fácil de usar, fácil de entender e útil.</li>
    <li><strong>Acessibilidade:</strong> Desenhar para que mais pessoas possam usar uma solução, incluindo pessoas com deficiência, pessoas idosas ou com pouca experiência tecnológica.</li>
    <li><strong>Persona:</strong> Descrição de um tipo de usuário que ajuda a imaginar para quem estamos desenhando.</li>
    <li><strong>Fluxo de usuário:</strong> Sequência de passos que uma pessoa segue para completar uma tarefa.</li>
    <li><strong>Wireframe:</strong> Desenho simples de uma tela usado para organizar botões, textos e informações.</li>
    <li><strong>Mockup:</strong> Tela mais elaborada que mostra como o design pode parecer.</li>
    <li><strong>Protótipo:</strong> Versão de teste da solução, interativa ou visual.</li>
    <li><strong>Pitch:</strong> Apresentação curta para explicar uma ideia de forma clara e convincente.</li>
  </ul>

