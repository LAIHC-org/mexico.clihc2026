  <h2>9. Quick glossary</h2>
  <ul>
    <li><strong>HCI:</strong> Human-Computer Interaction: how people use technology and how we can design it better.</li>
    <li><strong>UX:</strong> User Experience: how a person feels when using an app, website, or digital service.</li>
    <li><strong>Usability:</strong> Making something easy to use, easy to understand, and useful.</li>
    <li><strong>Accessibility:</strong> Designing so more people can use a solution, including people with disabilities, older adults, or people with limited technology experience.</li>
    <li><strong>Persona:</strong> A description of a type of user that helps us imagine who we are designing for.</li>
    <li><strong>User flow:</strong> The sequence of steps a person follows to complete a task.</li>
    <li><strong>Wireframe:</strong> A simple drawing of a screen used to organize buttons, text, and information.</li>
    <li><strong>Mockup:</strong> A more detailed screen showing how the design could look.</li>
    <li><strong>Prototype:</strong> A test version of the solution, either interactive or visual.</li>
    <li><strong>Pitch:</strong> A short presentation that explains an idea clearly and convincingly.</li>
  </ul>

