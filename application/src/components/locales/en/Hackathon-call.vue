  <h2>1. What is this hackathon?</h2>
  <p>The User Experience and Artificial Intelligence Hackathon is an official activity within the 12th Latin American Conference on Human-Computer Interaction (CLIHC 2026), to be held in Oaxaca, Mexico.</p>
  <p>It is intended for high school, undergraduate, and graduate students who want to imagine, design, and present technology solutions that are useful in real life.</p>
  <p>You do not need to be an expert in coding, design, or AI. What matters is learning, working as a team, and proposing ideas that help people.</p>
  <p>During the hackathon, you will learn to think like a human-centered technology designer: observing real problems, understanding users, and creating clear, useful, accessible, and inclusive proposals.</p>

  <h2>2. Objective and general approach</h2>
  <p>The goal is to design a technology proposal to improve digital public services related to mobility and public transportation in the city of Oaxaca.</p>
  <p>Your proposal should show how an app could become easier to use, clearer, more accessible, and more useful for its users.</p>
  <p>The main focus is not building a full application. The focus is understanding a real problem, thinking about the people affected by it, designing a possible solution, creating screens or prototypes, using digital tools and AI creatively and responsibly, and presenting the proposal clearly to a jury.</p>

